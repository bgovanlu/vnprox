#!/usr/bin/env bash
# Regenerates THIRD-PARTY-LICENSES.md from the real dependency trees.
#
# Hand-maintaining an attribution file guarantees it drifts, and an
# attribution file that has drifted is worse than none: it makes a false
# statement about what is being redistributed. This reads `go list -m all`
# and npm's own production tree instead, so the file can be regenerated and
# diffed in review.
#
# Usage: make third-party   (or: packaging/bin/gen-third-party-licenses.sh)
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
OUT="$REPO_ROOT/THIRD-PARTY-LICENSES.md"
cd "$REPO_ROOT"

tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

{
  cat <<'HEADER'
# Third-party licenses

vnprox is distributed under the Apache License 2.0 (see `LICENSE` and `NOTICE`).
The artifacts it ships — the `vnproxd` binary and the embedded single-page
application — bundle third-party open-source components, listed here with the
licence each is distributed under.

**This file is generated.** Run `make third-party` to regenerate it after a
dependency change; a hand-edited copy will be overwritten. The generator is
`packaging/bin/gen-third-party-licenses.sh`.

## Components requiring particular attention

| Component | Licence | Why it is called out |
|---|---|---|
| `elkjs` | EPL-2.0 | Weak (file-level) copyleft, and it **does** ship inside the SPA bundle — it is the graph layout engine. Using it imposes no obligation on vnprox's own source, but recipients must be able to obtain the EPL text and elkjs's own source. Both are linked below. |
| `dompurify` | MPL-2.0 OR Apache-2.0 | Dual-licensed; vnprox elects **Apache-2.0**, matching this project's own licence. |
| `monaco-editor` | MIT | Ships as its own lazily-loaded chunk rather than in the main bundle. |
| Proxmox VE | AGPL-3.0 | **Not bundled and not linked.** vnprox interoperates with Proxmox VE only over its published HTTP API and on-disk configuration files, so no AGPL obligation attaches. See `NOTICE`. |

Full licence texts: [Apache-2.0](https://www.apache.org/licenses/LICENSE-2.0) ·
[MIT](https://opensource.org/license/mit) · [ISC](https://opensource.org/license/isc-license-txt) ·
[BSD-3-Clause](https://opensource.org/license/bsd-3-clause) ·
[BSD-2-Clause](https://opensource.org/license/bsd-2-clause) ·
[0BSD](https://opensource.org/license/0bsd) ·
[MPL-2.0](https://www.mozilla.org/en-US/MPL/2.0/) ·
[EPL-2.0](https://www.eclipse.org/legal/epl-2.0/) — elkjs source:
<https://github.com/kieler/elkjs>

HEADER

  echo "## Go modules (\`vnproxd\`, \`vnproxctl\`)"
  echo
  echo "Modules in the build graph, from \`go list -m all\`. Includes"
  echo "test-only and transitive modules; not all are linked into the shipped"
  echo "binaries."
  echo
  echo "| Module | Version |"
  echo "|---|---|"
  go list -m -f '{{.Path}}|{{.Version}}' all 2>/dev/null \
    | grep -v '^github.com/bgovanlu/vnprox' \
    | sort -f \
    | while IFS='|' read -r path ver; do
        printf '| `%s` | %s |\n' "$path" "$ver"
      done

  echo
  echo "## npm packages bundled into the SPA"
  echo
  echo "Production dependency tree only (\`license-checker --production\`)."
  echo "Build- and test-only tooling — Vite, Vitest, Playwright, ESLint,"
  echo "TypeScript, axe-core, lightningcss — is **not** redistributed and is"
  echo "therefore excluded."
  echo
  echo "| Package | Version | Licence |"
  echo "|---|---|---|"
  (
    cd web
    npx --yes license-checker --production --json 2>/dev/null
  ) | node -e '
let s = "";
process.stdin.on("data", (d) => (s += d)).on("end", () => {
  const j = JSON.parse(s);
  const rows = Object.entries(j)
    .filter(([k]) => !k.startsWith("vnprox-web@"))
    .map(([k, v]) => {
      const i = k.lastIndexOf("@");
      return { name: k.slice(0, i), ver: k.slice(i + 1), lic: v.licenses || "UNKNOWN" };
    })
    .sort((a, b) => a.name.localeCompare(b.name) || a.ver.localeCompare(b.ver));
  for (const r of rows) console.log(`| \`${r.name}\` | ${r.ver} | ${r.lic} |`);
});'

  echo
  echo "---"
  echo
  echo "Generated by \`packaging/bin/gen-third-party-licenses.sh\`."
} > "$tmp"

mv "$tmp" "$OUT"
trap - EXIT
echo "wrote $OUT ($(wc -l < "$OUT") lines)"
